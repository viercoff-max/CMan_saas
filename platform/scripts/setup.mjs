// One-time local setup: creates .env.local with random secrets. Safe to re-run (never overwrites).
// Production: see docs/RUNBOOK.md (move .env.local and DATA_DIR out of OneDrive, then rotate the secrets).
import fs from "node:fs";
import crypto from "node:crypto";

const file = ".env.local";
if (fs.existsSync(file)) {
  console.log(".env.local already exists, leaving it untouched.");
  const env = fs.readFileSync(file, "utf8");
  if (/^META_APP_SECRET=\s*$/m.test(env)) console.warn("WARNING: META_APP_SECRET is empty. Set it before connecting real Meta channels.");
  if (/OneDrive|Dropbox|Google Drive/i.test(process.cwd()) && !/^DATA_DIR=\S+/m.test(env))
    console.warn("WARNING: this folder is synced to the cloud and DATA_DIR is not set. Customer data would sync too. See docs/RUNBOOK.md.");
  process.exit(0);
}
const rand = (n) => crypto.randomBytes(n).toString("base64url");
const body = `# Generated by npm run setup. Never commit this file. Keep it OUT of OneDrive in production.
APP_SECRET=${rand(32)}
ADMIN_EMAIL=admin@chefman.local
# Used only to create the admin on first start. Delete this line after your first login.
ADMIN_PASSWORD=${rand(12)}
TENANT_NAME=Chefman
PUBLIC_URL=http://localhost:3000

# Data folder (database, uploads, outbox). Empty = ./data. Production: a non-synced folder, e.g. C:\\ProgramData\\SocialInbox\\data
DATA_DIR=

# Retention for npm run purge (days; minimum 30)
RETENTION_DAYS=90

# AI (leave empty to use the built-in offline fallback replies)
OPENAI_API_KEY=
OPENAI_MODEL=gpt-4.1-mini

# Meta (WhatsApp / Instagram / Messenger) webhook. REQUIRED before real traffic.
META_VERIFY_TOKEN=${rand(16)}
META_APP_SECRET=
# Leave empty. "1" only for local testing without Meta (ignored when PUBLIC_URL is not localhost).
ALLOW_UNSIGNED_WEBHOOKS=

# Shopify one-button connect (OAuth). Leave empty to use the manual token option.
SHOPIFY_API_KEY=
SHOPIFY_API_SECRET=
`;
fs.writeFileSync(file, body, { mode: 0o600 });
console.log("Created .env.local. The admin login is in that file (ADMIN_EMAIL / ADMIN_PASSWORD).");
if (/OneDrive|Dropbox|Google Drive/i.test(process.cwd()))
  console.warn("WARNING: this folder is synced to the cloud. Before real customers, follow docs/RUNBOOK.md to move data and secrets out.");
